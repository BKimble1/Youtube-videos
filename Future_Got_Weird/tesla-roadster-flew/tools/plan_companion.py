    ('c12', ('b2', 'This', 1), 'timeline', {}, {'y17': ('b2', '2017', 0), 'y28': ('b2', '2028', 0)}),
    ('c13', ('b3', 'Start', 0), 'suction', {}, {'grav': ('b3', 'gravity', 0), 'fan': ('b3', 'fans', 0), 'gap': ('b3', 'thin', 0),
                                                'push': ('b3', 'normal', 1), 'two': ('b3', 'two', 0), 'double': ('b3', 'double', 0)}),
    ('c14', ('b3', 'Racing', 0), 'fancar', {}, {'rules': ('b3', 'rules', 0)}),
    ('c15', ('b3', 'And', 0), 'separate', {}, {'sep': ('b3', 'separate', 0)}),
