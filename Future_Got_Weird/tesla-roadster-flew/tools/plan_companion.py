def at(c):
    return c if isinstance(c, (int, float)) else cue(*c)

shots = []
last_word_end = words[-1]['e']
for i, (sid, start, kind, extra, cues) in enumerate(PLAN):
    a = 0.0 if start == 0.0 else (last_word_end + 0.35 if start == 'end' else max(0.0, at(start) - LEAD))
    shots.append({'id': sid, 'a': round(a, 3), 'kind': kind, **extra, 'cues': {k: round(at(v), 3) for k, v in cues.items()}})
for i, s in enumerate(shots):
    s['b'] = shots[i + 1]['a'] if i + 1 < len(shots) else round(DUR, 3)
json.dump({'_readme': 'Generated by tools/plan_companion.py from cue words; do not edit by hand.', 'duration': round(DUR, 3), 'shots': shots},
          open(os.path.join(ROOT, 'source/src/data/companion_shots.json'), 'w'), indent=1)
for s in shots:
    print(f"{s['id']} {s['a']:7.2f}-{s['b']:7.2f} ({s['b'] - s['a']:5.2f}s) {s['kind']:9s} {s.get('slot', '')}")
