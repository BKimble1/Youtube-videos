#!/usr/bin/env python3
"""V2: generate script/CUE_SHEET_V2.md from audio/v2/cues.json (exported by source/scripts/export_cues.ts from the
same TypeScript modules the picture renders) plus the per-unit staging notes below, and list the purpose of every
lengthened narration pause (audio/narration_v2/VOICE_EDIT_LOG.json). Frames are start-inclusive / end-exclusive.
Usage: python3 tools/make_cue_sheet_v2.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
D = json.load(open(ROOT / 'audio' / 'v2' / 'cues.json'))
W = json.load(open(ROOT / 'audio' / 'narration_v2' / 'narration_words_final.json'))['words']
G = json.load(open(ROOT / 'audio' / 'narration_v2' / 'VOICE_EDIT_LOG.json'))
FPS = D['fps']

# unit id -> (camera, source)
NOTES = {
    'U01': ('Follows the wrist down: z 1.10 -> 1.50, spline through its marks', 'StreetShots.tsx FALL keys (left hand plants at HAND_PLANT), Man.tsx, Head.tsx, Dog.tsx'),
    'U02': ('Two-shot of his face and the attached forearm (z 2.7), then along the upper arm and forearm onto the band (z 8.6)', 'Journey.tsx camA, Device.tsx Wrist3D inside Man.tsx'),
    'U03': ('Push to z 14 while the case turns about the arm axis (roll 0 -> 90 deg); diagram backdrop fades in behind the forearm', 'Device.tsx (roll), Interior.tsx SectionLayers, Scene.tsx Backdrop'),
    'U04': ('Push onto the port and follow the stream down into the vessel (z 17 -> 42)', 'Interior.tsx PortModule, StreamDraw, VesselTube'),
    'U05': ('Exponential dive into the vessel (z 42 -> ~190) with a roll that turns the flow to screen-up', 'Journey.tsx diveCam'),
    'U06': ('Tracks the hero sensor along the curved vessel; slows and closes in at the wall', 'Journey.tsx rideCam, Interior.tsx VesselTube (occluder, wall cells, hero signal)'),
    'U07': ('Invisible switch to the front-view x-ray deep inside the vessel; exponential pull back along the vessel to z 2.0, roll back to 0', 'Journey.tsx pullCam, Interior.tsx ArmXray / ChestXray'),
    'U08': ('Moves to the liver (z 3.0 -> 4.4)', 'Interior.tsx ChestXray (organ dim, sensors)'),
    'U09': ('Moves to the heart (z 6.4 -> 7.0)', 'Interior.tsx Heart2 (beat -> irregular), sensors cyan -> red'),
    'U10': ('Follows the red pulse from the heart down the arm (z 4.4) onto the band (z 8.6 -> 11); red ring on arrival', 'Journey.tsx camB, VesselTube pulse, lib/device.ts'),
    'U11': ('Push onto the seconds digits (z 11.6 -> 14.5)', 'Journey.tsx camB'),
    'U12': ('Cut to his face as his eyes open; the camera follows his gaze down to a face-and-band two-shot (z 3.8), then onto the band (z 7.4)', 'Journey.tsx CHAIN keys, lyingExpr (gaze), Device roll toward him'),
    'U13': ('On the band; the blue ring opens a circular window onto the map (clip, no crossfade)', 'Rescue.tsx RingWipe, Film.tsx'),
    'U14': ('Starts on his lawn (his pin where the band was on screen), pulls out to frame his lawn and the hub, then dives into the hub', 'Rescue.tsx MapV2, mapCam'),
    'U15': ('Cut on the hub to the rooftop pad (z 1.5) rising with the drone; tracks it across the street (z 1.25)', 'Rescue.tsx LiftOff, Travel'),
    'U16': ('Medium on him lying (z 1.7 -> 2.0); the drone settles above and its light finds the band', 'Aftermath.tsx, Rescue.tsx DroneOver'),
    'U17': ('Push onto the band, tip to the underside section (z 15 -> 32), follow the wave along the vessel (z 24 -> 19), back along the arm to the band face (held timer, z 9.6)', 'Aftermath.tsx afterCam, Interior.tsx (treat, wave, dimFrom)'),
    'U18': ('Pull back to his upper body (z 2.5 -> 1.6) through the sit-up', 'Aftermath.tsx RECOVERY keys'),
    'U19': ('Onto the band across his knee (z 8.6 -> 9.2), then up to his face: face-and-band two-shot (z 2.5)', 'Aftermath.tsx afterCam, exprAt'),
    'U20': ('Holds the two-shot with a slow push (z 2.5 -> 2.8); dip to black over the last 16 frames', 'Aftermath.tsx, lib/device.ts glitch'),
}


def t(f):
    return f'{f / FPS:6.2f}'


def main():
    dv = D['device']
    lines = ['# Cue sheet: The Death Clock V2', '',
             f"Generated by `tools/make_cue_sheet_v2.py` from `audio/v2/cues.json` (exported by `source/scripts/export_cues.ts` from the same TypeScript modules the picture renders). {D['total_frames']} frames at {FPS} fps = {D['total_frames'] / FPS:.3f} s. Ranges are start-inclusive / end-exclusive.", '',
             '## Device states', '',
             f"- crimson from frame {dv['redAt']} ({dv['redAt'] / FPS:.2f} s), as the heart's signal reaches the band",
             f"- 00:02:14 appears at frame {dv['timerAt']} ({dv['timerAt'] / FPS:.2f} s, the word \"calculates\") and counts down at film speed",
             f"- diagnostic bar frames {dv['diag0']}-{dv['diag1']}; HELP ALERT SENT from frame {dv['alertAt']} ({dv['alertAt'] / FPS:.2f} s)",
             f"- timer held (blue, STABILIZING) from frame {dv['freezeAt']} ({dv['freezeAt'] / FPS:.2f} s), reading {D['countdown_at'][str(dv['freezeAt'])]:.2f} s (shown 00:01:59); never reaches zero",
             f"- green \"Life Expectancy: 42 Years\" from frame {dv['recoverAt']} ({dv['recoverAt'] / FPS:.2f} s); one \"?\" glitch frames {dv['glitchAt']}-{dv['glitchAt'] + dv['glitchLen'] - 1}",
             '', '## Lengthened narration pauses and what fills them', '',
             '| Between | Recorded | Edited | Picture and sound in the pause |', '|---|---|---|---|']
    for g in G['gaps']:
        if g['target_s'] is None:
            continue
        lines.append(f"| {g['between'][0]:.2f}-{g['between'][1]:.2f} s (take time) | {g['original_s']:.2f} s | {g['target_s']:.2f} s | {g['beat']} |")
    lines.append(f"| after the last word | | {G['tail_s']:.2f} s | the local \"?\" glitch, his uneasy look, a short dip to black |")
    lines += ['', 'Every other gap is kept as recorded (0.16-0.57 s).', '', '## Units', '']
    for uid, desc, a, b in D['units']:
        words = ' '.join(w['text'] for w in W if a / FPS <= w['start'] < b / FPS)
        cs = [c['text'] for c in D['captions'] if a / FPS <= c['start'] < b / FPS]
        sfx = [f"{c['id']}@{c['f']}" for c in D['cues'] if a <= c['f'] < b and c['kind'] not in ('clock', 'heartbeat')]
        ticks = sum(1 for c in D['cues'] if a <= c['f'] < b and c['kind'] == 'clock')
        beats = sum(1 for c in D['cues'] if a <= c['f'] < b and c['kind'] == 'heartbeat')
        cam, src = NOTES[uid]
        extra = '; '.join(x for x in [f'{ticks} clock ticks' if ticks else '', f'{beats} heartbeats' if beats else ''] if x)
        lines += [f'### {uid}  frames [{a}, {b})  {t(a)}-{t(b)} s', '',
                  f'- **Action:** {desc}',
                  f'- **VO:** {words or "(no speech)"}',
                  f'- **Camera:** {cam}',
                  f'- **Source:** {src}',
                  f'- **Captions:** {" | ".join(cs) or "(none start here)"}',
                  f'- **Sound:** {", ".join(sfx) or "-"}' + (f'; {extra}' if extra else ''), '']
    m = D['music']
    lines += ['## Music sections (s)', '', ', '.join(f'{k} {v:.2f}' for k, v in m.items()), '']
    (ROOT / 'script').mkdir(exist_ok=True)
    (ROOT / 'script' / 'CUE_SHEET_V2.md').write_text('\n'.join(lines))
    print('wrote script/CUE_SHEET_V2.md')


if __name__ == '__main__':
    main()
